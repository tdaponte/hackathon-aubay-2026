# 1. METADATA EXTRACTION ENGINE
# =====================================================================
def extract_form_metadata(page) -> list:
    """
    Scans the active web page for interactive elements and maps
    their structures, types, labels, and option configurations.
    """
    # Target text fields, textareas, dropdowns, and checkboxes
    interactive_elements = page.locator(
        "input[type='text'], input[type='email'], input[type='checkbox'], input:not([type]), textarea, select")
    count = interactive_elements.count()

    form_fields = []

    for i in range(count):
        element = interactive_elements.nth(i)
        element_id = element.get_attribute("id")
        input_type = element.get_attribute("type")
        tag_name = element.evaluate("el => el.tagName.toLowerCase()")

        # Classify the interactive element type
        field_type = "checkbox" if input_type == "checkbox" else tag_name

        if element_id:
            # Match standard labels using the 'for' attribute
            label_element = page.locator(f"label[for='{element_id}']")

            if label_element.count() > 0:
                label_text = label_element.inner_text().strip()
            else:
                # Fallback: Check if the element is nested within a label wrapper
                nested_label = page.locator(f"label:has(input#{element_id})")
                if nested_label.count() > 0:
                    label_text = nested_label.inner_text().strip()
                else:
                    label_text = f"Unnamed field ({element_id})"

            field_data = {
                "id": element_id,
                "label": label_text,
                "type": field_type,
                "options": []
            }

            # Extract options specifically for dropdown selects
            if field_type == "select":
                options_locator = element.locator("option")
                for j in range(options_locator.count()):
                    opt_text = options_locator.nth(j).inner_text().strip()
                    if opt_text:
                        field_data["options"].append(opt_text)

            form_fields.append(field_data)

    return form_fields


# =====================================================================
# 2. USER INTERACTION ENGINE
# =====================================================================
def prompt_user_for_inputs(form_metadata: list) -> dict:
    """
    Iterates through the extracted form metadata and interacts with
    the terminal user to cleanly gather structured configuration data.
    """
    print("\n📋 Form Found! Please fill in the configuration details below:")
    print(form_metadata)

    user_responses = {}

    for field in form_metadata:
        if field["type"] == "checkbox":
            choice = input(f"\n👉 Do you want to check [{field['label']}]? (yes/no): ").strip().lower()
            should_check = choice in ['yes', 'y', 'true', '1']
            user_responses[field["id"]] = (should_check, "checkbox")

        elif field["type"] == "select":
            print(f"\n👉 Dropdown found for [{field['label']}]. Available options:")
            for idx, opt in enumerate(field["options"], 1):
                print(f"  [{idx}] {opt}")

            choice = input(f"Enter the exact text or option number for [{field['label']}]: ")
            if choice.isdigit() and 1 <= int(choice) <= len(field["options"]):
                user_responses[field["id"]] = (field["options"][int(choice) - 1], "select")
            else:
                user_responses[field["id"]] = (choice, "select")
        else:
            user_val = input(f"\n👉 Enter text for [{field['label']}]: ")
            user_responses[field["id"]] = (user_val, "text")

    return user_responses


