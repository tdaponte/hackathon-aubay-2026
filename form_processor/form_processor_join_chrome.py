def fill_web_form(page, user_responses: dict):
    """
    Executes automation sequences inside the active web window
    using the structured dictionary map generated by user inputs.
    """
    print("\n🚀 Injecting collected data back into the web form...")

    for element_id, (value, field_type) in user_responses.items():
        selector = f"#{element_id}"

        if field_type == "checkbox":
            page.set_checked(selector, value)

        elif field_type == "select":
            print(f"  Selecting dropdown option '{value}' for {selector}...")
            try:
                # 1. First attempt: Try to match exactly by visible label text
                page.select_option(selector, label=value)
            except Exception:
                print(f"  ⚠️ Visible text '{value}' failed. Attempting alternative matching strategy...")
                try:
                    # 2. Second attempt: Fallback to matching by 'value' attribute or index string
                    page.select_option(selector, value=value)
                except Exception as e:
                    # 3. Third attempt: In case the options are slow to load dynamically,
                    # fetch all options directly from the element to find a partial match
                    options = page.locator(f"{selector} option").all_inner_texts()
                    cleaned_options = [o.strip() for o in options if o.strip()]

                    print(
                        f"  ❌ Selection failed completely. Available options in this dropdown were: {cleaned_options}")
                    print(f"  Skipping field {selector} due to mismatch error.")
        else:
            page.fill(selector, value)

    print("✅ Form update sequence finished!")


